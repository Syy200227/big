    plt.figure(figsize=(10.2, 6.0))
    plotted = False

    for spec in MODEL_SPECS:
        history = histories.get(spec.key)
        if not history:
            continue

        xs, ys, used_key = extract_series(history, "val_dice")
        if not ys:
            continue

        maximum_epoch = max(xs)
        progress = [
            100.0 * x / maximum_epoch
            for x in xs
        ]
        plt.plot(
            progress,
            moving_average(ys, smooth_window),
            linewidth=1.7,
            label=spec.label,
        )
        plotted = True

        best_epoch, best_dice, _ = best_value(history, "val_dice", "max")
