def is_evaluation_summary(document: Any) -> bool:
    if not isinstance(document, dict):
        return False
    return any(
        isinstance(document.get(key), dict)
        for key in ("summary", "probabilistic_summary", "evidence_summary")
    )


def summary_sample_counts(document: dict[str, Any]) -> set[int]:
    counts: set[int] = set()

    for key in ("summary", "probabilistic_summary", "evidence_summary"):
        mapping = document.get(key)
        if not isinstance(mapping, dict):
            continue
        for count_key in mapping:
            try:
                counts.add(int(count_key))
            except (TypeError, ValueError):
                continue

    return counts


def score_summary_candidate(
    path: Path,
    document: dict[str, Any],
    preferred_split: str,
    preferred_count: int,
    preferred_checkpoint_stem: str | None,
) -> tuple[int, int, int, float]:
    """Higher tuple is preferred.

    The exact checkpoint stem receives the largest path-name bonus. This
    prevents a V3 evidence-Dice or ECE evaluation from being selected when
    the requested comparison should use best_val_ged4_v3_evidential.pth.
    """
    score = 0
    split = str(document.get("split", "")).lower()
    counts = summary_sample_counts(document)

    if split == preferred_split.lower():
        score += 100
    elif split:
        score -= 20

    if preferred_count in counts:
        score += 50

    path_lower = str(path).lower()
    if "smoke" in path_lower:
        score -= 1000

    if preferred_checkpoint_stem:
        preferred_lower = preferred_checkpoint_stem.lower()
        if preferred_lower in path_lower:
            score += 500

        checkpoint_value = str(document.get("checkpoint", "")).lower()
        if preferred_lower in checkpoint_value:
            score += 500

    if "best_val_ged4" in path_lower or "ged_best" in path_lower:
        score += 40
    if "best" in path_lower:
        score += 8
    if "latest" in path_lower:
        score -= 10

    maximum_count = max(counts) if counts else 0
    num_cases = int(document.get("num_cases", 0) or 0)
    modification_time = path.stat().st_mtime

    return score, maximum_count, num_cases, modification_time


def find_best_evaluation_summary(
    result_dir: Path,
    preferred_split: str,
    preferred_count: int,
    preferred_checkpoint: str | None,
) -> tuple[Path | None, dict[str, Any] | None, list[Path]]:
    candidates: list[tuple[Path, dict[str, Any]]] = []

    if not result_dir.exists():
        return None, None, []

    for path in result_dir.rglob("summary.json"):
        try:
            document = load_json(path)
        except Exception:
            continue
        if is_evaluation_summary(document):
            candidates.append((path, document))

    if not candidates:
        return None, None, []

    preferred_stem = (
        Path(preferred_checkpoint).stem
        if preferred_checkpoint is not None
        else None
    )

    candidates.sort(
        key=lambda item: score_summary_candidate(
            item[0],
            item[1],
            preferred_split,
            preferred_count,
            preferred_stem,
        ),
        reverse=True,
    )

    selected_path, selected_document = candidates[0]
    return (
        selected_path,
        selected_document,
        [path for path, _ in candidates],
    )


def extract_branch_summaries(
    spec: ModelSpec,
    document: dict[str, Any],
) -> list[tuple[str, dict[str, Any]]]:
    branches: list[tuple[str, dict[str, Any]]] = []

    ordinary = document.get("summary")
    if isinstance(ordinary, dict):
        branches.append((spec.label, ordinary))

    probabilistic = document.get("probabilistic_summary")
    if isinstance(probabilistic, dict):
        branches.append((f"{spec.label} - probabilistic", probabilistic))

    evidence = document.get("evidence_summary")
    if isinstance(evidence, dict):
        branches.append((f"{spec.label} - evidence", evidence))

    return branches


def metric_mean(
    summary: dict[str, Any],
    count: int,
    metric: str,
) -> float | None:
    count_item = summary.get(str(count))
    if not isinstance(count_item, dict):
        return None

    metric_item = count_item.get(metric)
    if isinstance(metric_item, dict):
        return safe_float(metric_item.get("mean"))
    return safe_float(metric_item)


def available_counts(summary: dict[str, Any]) -> list[int]:
    counts: list[int] = []
    for key in summary:
        try:
            counts.append(int(key))
        except (TypeError, ValueError):
            continue
    return sorted(set(counts))


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    if not rows:
        return

    all_keys: list[str] = []
    seen: set[str] = set()

    for row in rows:
        for key in row:
            if key not in seen:
                seen.add(key)
                all_keys.append(key)

    with path.open("w", encoding="utf-8-sig", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=all_keys)
        writer.writeheader()
        writer.writerows(rows)


def plot_evaluation_comparison(
    selected_documents: dict[str, tuple[Path, dict[str, Any]]],
    output_dir: Path,
    preferred_count: int,
) -> tuple[list[str], list[dict[str, Any]]]:
    branches: list[tuple[str, str, dict[str, Any], Path]] = []

    for spec in MODEL_SPECS:
        selected = selected_documents.get(spec.key)
        if selected is None:
            continue
        path, document = selected
        for branch_label, summary in extract_branch_summaries(spec, document):
            branches.append((spec.key, branch_label, summary, path))

    generated: list[str] = []
    rows: list[dict[str, Any]] = []

    if not branches:
        return generated, rows

    # Curves against sample count.
    for metric, display_name, direction in EVALUATION_METRICS:
        plt.figure(figsize=(10.2, 6.0))
        plotted = False

        for model_key, label, summary, path in branches:
            counts = available_counts(summary)
            xs: list[int] = []
            ys: list[float] = []

            for count in counts:
                value = metric_mean(summary, count, metric)
                if value is None:
                    continue
                xs.append(count)
                ys.append(value)
                rows.append(
                    {
                        "model_key": model_key,
                        "branch": label,
                        "sample_count": count,
                        "metric": metric,
                        "mean": value,
                        "summary_path": str(path),
                    }
                )

            if not ys:
                continue

            plt.plot(xs, ys, marker="o", linewidth=1.7, label=label)
            plotted = True

        if not plotted:
            plt.close()
            continue

        qualifier = (
            "lower is better"
            if direction == "lower"
            else "higher is better"
            if direction == "higher"
            else "descriptive"
        )
        plt.title(f"Prior-sampling {display_name} ({qualifier})")
        plt.xlabel("Number of prior samples")
        plt.ylabel(display_name)
        plt.grid(True, alpha=0.25)
        plt.legend()
        filename = f"evaluation_{metric}_vs_samples.png"
        save_figure(output_dir / filename)
        generated.append(filename)

    # Bar plots at the preferred sample count. Models without that count
    # are omitted rather than silently substituting a different count.
    for metric, display_name, direction in EVALUATION_METRICS:
        labels: list[str] = []
        values: list[float] = []

        for _, label, summary, _ in branches:
            value = metric_mean(summary, preferred_count, metric)
            if value is None:
                continue
            labels.append(label)
            values.append(value)

        if len(values) < 2:
            continue

        plt.figure(figsize=(11.2, 6.1))
        plt.bar(range(len(values)), values)
        plt.xticks(range(len(values)), labels, rotation=18, ha="right")
        plt.ylabel(f"{display_name} @ {preferred_count} samples")
        qualifier = (
            "lower is better"
            if direction == "lower"
            else "higher is better"
            if direction == "higher"
            else "descriptive"
        )
        plt.title(
            f"{display_name} at {preferred_count} prior samples "
            f"({qualifier})"
        )
        plt.grid(True, axis="y", alpha=0.25)
        annotate_bars(values)
        filename = f"evaluation_{metric}_at_{preferred_count}.png"
        save_figure(output_dir / filename)
        generated.append(filename)

    return generated, rows


def write_detection_report(
    path: Path,
    project_root: Path,
    histories: dict[str, list[dict[str, Any]]],
    history_paths: dict[str, Path],
    selected_documents: dict[str, tuple[Path, dict[str, Any]]],
    all_candidates: dict[str, list[Path]],
) -> None:
    lines: list[str] = []
    lines.append(f"Project root: {project_root}")
    lines.append("")

    for spec in MODEL_SPECS:
        result_dir = project_root / spec.relative_dir
        lines.append(f"[{spec.label}]")
        lines.append(f"Result directory: {result_dir}")
        lines.append(
            "Preferred evaluation checkpoint: "
            f"{spec.primary_evaluation_checkpoint}"
        )
        lines.append("Exact expected top-level files:")
        for filename in spec.expected_files:
            status = "OK" if (result_dir / filename).is_file() else "MISSING"
            lines.append(f"  [{status}] {filename}")

        history_path = history_paths.get(spec.key)
        if history_path is None:
            lines.append("History: NOT FOUND")
        else:
            lines.append(f"History: {history_path}")
            history = histories[spec.key]
            lines.append(f"History epochs: {len(history)}")
            for alias_name in (
                "train_dice",
                "val_dice",
                "val_ged2",
                "val_prior_effective_components",
            ):
                key = first_present_key(history, alias_name)
                lines.append(f"  {alias_name}: {key or 'not found'}")

        selected = selected_documents.get(spec.key)
        if selected is None:
            lines.append("Evaluation summary: NOT FOUND")
        else:
            selected_path, document = selected
            lines.append(f"Selected evaluation summary: {selected_path}")
            lines.append(f"  split: {document.get('split')}")
            lines.append(
                f"  sample counts: {sorted(summary_sample_counts(document))}"
            )

        candidates = all_candidates.get(spec.key, [])
        if candidates:
            lines.append("All detected evaluation summaries:")
            for candidate in candidates:
                lines.append(f"  - {candidate}")

        lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")



