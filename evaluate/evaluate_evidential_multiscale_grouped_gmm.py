def safe_float(value: Any) -> float | None:
    if value is None or isinstance(value, bool):
        return None
    try:
        result = float(value)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(result):
        return None
    return result


def flatten_mapping(
    value: Any,
    prefix: str = "",
) -> dict[str, Any]:
    """Flatten nested dictionaries using underscore-separated keys."""
    flattened: dict[str, Any] = {}

    if not isinstance(value, dict):
        return flattened

    for key, item in value.items():
        full_key = f"{prefix}_{key}" if prefix else str(key)
        if isinstance(item, dict):
            flattened.update(flatten_mapping(item, full_key))
        else:
            flattened[full_key] = item

    return flattened


def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as file:
        return json.load(file)


def load_history(path: Path) -> list[dict[str, Any]]:
    document = load_json(path)
    if not isinstance(document, list) or not document:
        raise ValueError(f"{path} must contain a non-empty JSON list.")

    records: list[dict[str, Any]] = []
    for index, item in enumerate(document):
        if not isinstance(item, dict):
            raise ValueError(f"{path}: record {index} is not a dictionary.")
        flattened = flatten_mapping(item)
        flattened.update(
            {
                key: value
                for key, value in item.items()
                if not isinstance(value, dict)
            }
        )
        records.append(flattened)

    records.sort(key=lambda record: safe_float(record.get("epoch")) or 0.0)
    return records


def first_present_key(
    history: list[dict[str, Any]],
    alias_name: str,
) -> str | None:
    candidates = ALIASES[alias_name]
    for candidate in candidates:
        if any(safe_float(record.get(candidate)) is not None for record in history):
            return candidate
    return None


def extract_series(
    history: list[dict[str, Any]],
    alias_name: str,
) -> tuple[list[float], list[float], str | None]:
    key = first_present_key(history, alias_name)
    if key is None:
        return [], [], None

    epoch_key = first_present_key(history, "epoch") or "epoch"
    xs: list[float] = []
    ys: list[float] = []

    for index, record in enumerate(history, start=1):
        x = safe_float(record.get(epoch_key))
        y = safe_float(record.get(key))
        if y is None:
            continue
        xs.append(float(index) if x is None else x)
        ys.append(y)

    return xs, ys, key


def moving_average(values: list[float], window: int) -> list[float]:
    if window <= 1:
        return list(values)

    result: list[float] = []
    running_sum = 0.0

    for index, value in enumerate(values):
        running_sum += value
        if index >= window:
            running_sum -= values[index - window]
        width = min(index + 1, window)
        result.append(running_sum / float(width))

    return result


def save_figure(path: Path) -> None:
    plt.tight_layout()
    plt.savefig(path, dpi=220, bbox_inches="tight")
    plt.close()


def best_value(
    history: list[dict[str, Any]],
    alias_name: str,
    direction: str,
) -> tuple[int | None, float | None, str | None]:
    xs, ys, key = extract_series(history, alias_name)
    if not ys:
        return None, None, key

    pairs = [(int(round(x)), y) for x, y in zip(xs, ys)]
    if direction == "min":
        epoch, value = min(pairs, key=lambda item: item[1])
    else:
        epoch, value = max(pairs, key=lambda item: item[1])
    return epoch, value, key


def final_value(
    history: list[dict[str, Any]],
    alias_name: str,
) -> tuple[int | None, float | None, str | None]:
    xs, ys, key = extract_series(history, alias_name)
    if not ys:
        return None, None, key
    return int(round(xs[-1])), ys[-1], key


def annotate_bars(values: list[float]) -> None:
    if not values:
        return
    span = max(values) - min(values)
    offset = max(span * 0.025, 0.003)
    for index, value in enumerate(values):
        plt.text(index, value + offset, f"{value:.4f}", ha="center", va="bottom")


